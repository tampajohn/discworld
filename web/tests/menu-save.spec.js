import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

test('native menu v10 save restores exact pixels and exports unchanged in WASM', async ({ page }, testInfo) => {
  const checkpoint = process.env.DISCWORLD_TEST_MENU_SAVE;
  test.skip(!checkpoint, 'requires a menu checkpoint generated by the original-asset Rust test');
  const root = path.resolve(import.meta.dirname, '../..');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.locator('#iso').setInputFiles(process.env.DISCWORLD_TEST_ISO || path.join(root, "Terry Pratchett's Discworld (1995)(Psygnosis).iso"));
  await page.locator('#font').setInputFiles(process.env.DISCWORLD_TEST_SOUNDFONT || path.join(root, 'assets/soundfonts/TimGM6mb.sf2'));
  await page.locator('#initial-save').setInputFiles(checkpoint);
  await page.locator('#open').click();
  await expect(page.locator('#player')).toBeVisible({ timeout: 60000 });
  const expected = await fs.readFile(`${checkpoint}.rgba`);
  expect(await page.evaluate(expected => {
    const canvas = document.querySelector('#game');
    const actual = canvas.getContext('2d').getImageData(0, 0, 320, 200).data;
    return actual.length === expected.length && actual.every((value, i) => value === expected[i]);
  }, Array.from(expected))).toBe(true);
  await page.locator('#game').screenshot({ path: path.join(root, `assets/previews/browser-${testInfo.project.name}-menu-v10.png`) });
  await page.locator('summary').click();
  const download = page.waitForEvent('download');
  await page.locator('#export').click();
  expect(await fs.readFile(await (await download).path())).toEqual(await fs.readFile(checkpoint));
  expect(errors).toEqual([]);
});
